def get_game_poster_url(game_slug):
    """
    Get high-quality poster URL for a game by slug.
    Returns CDN URL or empty string if not found.
    """
    return GAME_POSTER_URLS.get(game_slug, '')


def update_all_game_posters():
    """
    Update cover_url for all games in database with high-quality poster URLs.
    Returns count of updated games.
    """
    from apps.games.models import Game
    
    updated_count = 0
    for game in Game.objects.all():
        poster_url = get_game_poster_url(game.slug)
        if poster_url and game.cover_url != poster_url:
            game.cover_url = poster_url
            game.save(update_fields=['cover_url'])
            updated_count += 1
    
    return updated_count
